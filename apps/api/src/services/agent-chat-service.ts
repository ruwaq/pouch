  /**
   * 🔄 Handles token swap requests (e.g. "swap 1 ARB for ETH").
   * Uses Uniswap V3 on Arbitrum to convert ARB → ETH for gas purposes.
   */
  private async handleSwap(userId: string, intent: CashOutIntent): Promise<Result<AgentChatResponse, DomainError>> {
    const balance = await this.balanceService.getBalance(userId);
    if (!isOk(balance)) {
      const reply = await this.buildReply(intent, userId, 'error', { error: 'Could not read balance' });
      return this.emptyResult(intent, reply);
    }

    const b = balance.value;
    const tokenIn = (intent.token ?? intent.brand ?? 'ARB').toUpperCase();
    const tokenOut = (intent.targetToken ?? 'ETH').toUpperCase();
    const amount = intent.amount.value;
    const chainId = intent.chainId ?? 42161;

    // ── Validate swap direction ──────────────────────────────────
    if (tokenIn !== 'ARB' || tokenOut !== 'ETH') {
      const reply = await this.buildReply(intent, userId, 'error', {
        error: `Swap only supports ARB → ETH on Arbitrum right now. You asked for ${tokenIn} → ${tokenOut}.`,
      });
      return this.emptyResult(intent, reply);
    }

    // ── Find source wallet ───────────────────────────────────────
    let fromLabel = intent.fromLabel?.trim();
    if (!fromLabel) {
      const arbAssets = b.assets.filter(
        (a) => a.symbol === 'ARB' && a.chainId === chainId,
      );
      arbAssets.sort((a, b) => b.usdValue - a.usdValue);
      fromLabel = arbAssets[0]?.walletLabel ?? 'Wallet 1';
    }

    const matchedFrom = this.resolveWalletLabel(fromLabel, b);
    if (!matchedFrom) {
      const reply = await this.buildReply(intent, userId, 'error', {
        error: `Wallet "${fromLabel}" not found.`,
      });
      return this.emptyResult(intent, reply);
    }

    // ── Validate ARB balance ────────────────────────────────────
    const arbAssets = b.assets.filter(
      (a) => a.walletLabel === matchedFrom && a.symbol === 'ARB' && a.chainId === chainId,
    );
    const availableARB = arbAssets.reduce((sum, a) => sum + a.amount, 0);

    if (availableARB < amount) {
      const reply = await this.buildReply(intent, userId, 'insufficient', {
        balance: b,
        error: `${matchedFrom} has ${availableARB.toFixed(4)} ARB — not enough for ${amount} ARB.`,
      });
      return this.emptyResult(intent, reply);
    }

    // ── Security check ──────────────────────────────────────────
    if (this.securityChecker) {
      const secCheck = await this.securityChecker.check(intent, userId);
      if (isOk(secCheck) && secCheck.value.verdict === 'BLOCK') {
        const blockedCheck = secCheck.value.checks.find((c) => c.verdict === 'BLOCK');
        const reply = await this.buildReply(intent, userId, 'error', {
          error: blockedCheck?.detail ?? 'Transaction blocked by security policy',
        });
        return this.emptyResult(intent, reply);
      }
    }

    // ── Build confirmation ──────────────────────────────────────
    const planSummary = `swap ${amount} ${tokenIn} → ${tokenOut} from ${matchedFrom} on Arbitrum`;

    const resolvedIntent: CashOutIntent = {
      ...intent,
      token: tokenIn,
      targetToken: tokenOut,
      fromLabel: matchedFrom,
      chainId,
    };

    pendingConfirmations.set(userId, { intent: resolvedIntent, planSummary, type: 'swap' });

    const reply = await this.buildReply(resolvedIntent, userId, 'swap_confirmation', {
      balance: b,
      planSummary,
    });

    return this.emptyResult(resolvedIntent, reply, {
      phase: 'swap_confirmation',
      balanceSnapshot: b,
      planSummary,
    });
  }

